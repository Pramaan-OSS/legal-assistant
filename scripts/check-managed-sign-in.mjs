import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const origin='http://localhost:3000';
const good=`offline.${Buffer.from(JSON.stringify({sub:'offline-managed-reader',iss:'https://signin.example.test',aud:'https://signin.example.test'})).toString('base64url')}.offline`;
const browser=await chromium.launch({headless:true});const page=await browser.newPage();
let refused=true;let exchanges=0;
mkdirSync('.scratch/verification',{recursive:true});
await page.route('**/*',async route=>{
 const request=route.request(),url=new URL(request.url());
 if(url.origin===origin)return route.continue();
 if(url.hostname!=='signin.example.test')return route.abort();
 const headers={'Content-Type':'application/json','Access-Control-Allow-Origin':origin,'Access-Control-Allow-Credentials':'true','Access-Control-Allow-Headers':'content-type','Access-Control-Allow-Methods':'GET, POST, OPTIONS','Access-Control-Expose-Headers':'set-auth-jwt'};
 if(request.method()==='OPTIONS')return route.fulfill({status:204,headers});
 const user={id:'offline-managed-reader',email:'reader@example.test',emailVerified:true,name:'Reader',createdAt:new Date().toISOString(),updatedAt:new Date().toISOString()};
 if(url.pathname.endsWith('/token'))return route.fulfill({headers,json:{token:refused?'offline.invalid.offline':good}});
 if(url.pathname.endsWith('/get-session'))return route.fulfill({headers:{...headers,'set-auth-jwt':refused?'offline.invalid.offline':good},json:{user,session:{id:'offline-session',userId:user.id,expiresAt:new Date(Date.now()+3600000).toISOString(),token:'offline-browser-session'}}});
 if(url.pathname.endsWith('/sign-in/social'))return route.fulfill({headers,json:{redirect:true,url:origin+'/auth/managed/return'}});
 if(url.pathname.endsWith('/sign-in/email'))return route.fulfill({headers,json:{user,token:'offline-browser-session',redirect:false}});
 throw new Error('Unexpected managed sign-in request path');
});
page.on('response',response=>{if(response.url().endsWith('/api/auth/managed/redeem'))exchanges++;});
try {
 await page.goto(origin+'/login');
 await page.getByLabel('Email',{exact:true}).fill('reader@example.test');
 await page.getByLabel('Password',{exact:true}).fill('offline-check-password');
 let response=page.waitForResponse(r=>r.url().endsWith('/api/auth/managed/redeem'));
 await page.getByRole('button',{name:'Log in',exact:true}).click();
 assert.equal((await response).status(),401,'Altered token must be refused');
 await page.getByRole('alert').filter({hasText:/\S/}).first().waitFor();
 refused=false;response=page.waitForResponse(r=>r.url().endsWith('/api/auth/managed/redeem'));
 await page.getByRole('button',{name:'Log in',exact:true}).click();
 assert.equal((await response).status(),200,'Verified proof must open an app session');
 await page.goto(origin+'/onboarding/profile');
 await page.getByLabel('Name',{exact:true}).fill('Managed reader');
 await page.getByRole('button',{name:'Continue',exact:true}).click();
 await page.getByRole('button',{name:'Skip',exact:true}).click();
 await page.goto(origin+'/assistant');
 await page.getByPlaceholder('How can I help?').fill('Review my workspace.');await page.getByPlaceholder('How can I help?').press('Enter');
 await page.getByText('This is a local demonstration reply. Your workspace is ready.',{exact:true}).waitFor({timeout:30000});
 await page.screenshot({path:'.scratch/verification/managed-email.png'});
 await page.evaluate(()=>fetch('/api/auth/logout',{method:'POST',credentials:'include'}));
 await page.goto(origin+'/login');
 response=page.waitForResponse(r=>r.url().endsWith('/api/auth/managed/redeem'));
 await page.getByRole('button',{name:'Connected sign-in',exact:true}).click();
 assert.equal((await response).status(),200,'Social callback must open an app session');
 await page.getByPlaceholder('How can I help?').waitFor();
 await page.screenshot({path:'.scratch/verification/managed-social.png'});
 assert.equal(exchanges,3,'Each flow is redeemed once');
 console.log('PASS: refused token, managed email, app session, demonstration reply and social callback; no live service.');
}catch(error){await page.screenshot({path:'.scratch/verification/managed-failure.png'});console.log((await page.locator('body').innerText()).slice(0,2000));throw error;}finally{await browser.close();}
